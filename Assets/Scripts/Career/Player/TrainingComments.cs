        /// <summary>
        /// 段階を決める。相手の能力の絶対値と、主人公との差の両方を見る（多少ぶれる）。
        /// </summary>
        public static int Tier(int partnerStat, int playerStat, int noise)
        {
            int v = partnerStat + noise;
            int diff = v - playerStat;
            if (v >= 85 || diff >= 25) return 0;
            if (v >= 72 || diff >= 12) return 1;
            if (v >= 58 || diff >= 4) return 2;
            if (v >= 40) return 3;
            return 4;
        }

        public static string Line(int stat, int tier, string name, SeededRandom rng)
        {
            var options = Lines[stat][tier];
            return options[rng.Range(0, options.Length)].Replace("{n}", name);
        }

        /// <summary>練習相手のセリフ（性格・努力度で変わる）。</summary>
        public static string PartnerLine(NPCData n, bool partnerBetter, SeededRandom rng)
        {
            string[] lines;
            if (n.effort >= 75)
                lines = new[] { "まだまだ！ もう1本いこう！", "今日は日が暮れるまでやるぞ！", "練習は裏切らないからな。" };
            else if (n.effort < 35)
                lines = new[] { "ふー、今日はこのへんにしとこうぜ。", "練習ってだるくない？ 飲みに行こうよ。", "あー疲れた。明日は休みな。" };
            else switch (n.soccerPersonality)
            {
                case SoccerPersonality.Egoist:
                    lines = partnerBetter ? new[] { "見たか？ これが実力の差だ。", "学べることは多いぞ。" }
                                          : new[] { "……チッ、今日は調子が悪かっただけだ。", "次は負けねえからな。" };
                    break;
                case SoccerPersonality.MoodMaker:
                    lines = new[] { "いやー楽しかった！ また誘ってよ！", "お前と練習すると盛り上がるな！" };
                    break;
                case SoccerPersonality.Devoted:
                    lines = new[] { "いい練習になった。何か手伝えることがあったら言ってくれ。", "お前のプレー、合わせやすかったよ。" };
                    break;
                case SoccerPersonality.Sense:
                case SoccerPersonality.Gifted:
                    lines = new[] { "……今の、ちょっと面白かった。", "練習ってより、遊びだよね。サッカーは。" };
                    break;
                case SoccerPersonality.Fighter:
                    lines = new[] { "もっと本気で当たってこいよ！", "いい汗かいたな！" };
                    break;
                case SoccerPersonality.Hysteric:
                    lines = new[] { "なんで今のファウルなんだよ！ ……あ、審判いないか。", "イライラするけど、悪くない練習だった。" };
                    break;
                default:
                    lines = n.personality == Personality.Introvert
                        ? new[] { "……ありがとう。いい練習になった。", "……また、一緒にやってもいい？" }
                        : new[] { "いい練習になったよ。", "またやろうな。" };
                    break;
            }
            return lines[rng.Range(0, lines.Length)];
        }
